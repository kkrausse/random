// Builds the Android bridge into one self-contained classic script (no module imports, ES2020
// syntax) that the app ships as an asset and loads in a hidden WebView.

import { build } from "esbuild";
import { join } from "node:path";

const outfile = join(import.meta.dir, "..", "app", "src", "main", "assets", "reading-client.js");

const result = await build({
  entryPoints: [join(import.meta.dir, "src", "android-bridge.ts")],
  outfile,
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: false,
  legalComments: "none",
  banner: { js: "// Generated by `cd client && bun run build:android`. Do not edit; see client/README.md." },
  metafile: true
});

const bytes = result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].bytes;
console.log(`Built app/src/main/assets/reading-client.js (${bytes} bytes)`);
