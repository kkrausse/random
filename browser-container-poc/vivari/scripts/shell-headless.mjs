// Guest-worker job/lifecycle contract. Run with Node >=24 after build-runtime.
import assert from 'node:assert/strict';
import { Worker, MessageChannel } from 'node:worker_threads';
import { runtimeSourceUrl } from './runtime-source.mjs';
const { Kernel } = await import(runtimeSourceUrl('packages/kernel-host/kernel.js').href);
const { createKernelFs } = await import(runtimeSourceUrl('packages/kernel-host/kernel-fs.js').href);
const base = new URL('./', runtimeSourceUrl('scripts/process-worker.mjs'));
const workers = new Set();
const fsWorker = new Worker(new URL('fs-worker.mjs', base));
workers.add(fsWorker);
let onMessage = () => {};
const timeout = setTimeout(() => { console.error('shell contract timed out'); process.exit(1); }, 30000);
await new Promise((resolve, reject) => {
  fsWorker.on('error', reject);
  fsWorker.on('message', m => m.type === 'ready' ? resolve() : onMessage(m));
});
const bridge = createKernelFs(fsWorker);
onMessage = bridge.onMessage;
const output = new Map();
const append = (s, pid) => output.set(pid, (output.get(pid) || '') + s);
const kernel = new Kernel({ fs: bridge.fs, stdout: append, stderr: append, spawnWorker(info) {
  const w = new Worker(new URL('process-worker.mjs', base)); workers.add(w);
  w.on('message', m => info.on[m.type]?.(m));
  w.on('error', e => { console.error(e); kernel.stop(info.pid); });
  const { port1, port2 } = new MessageChannel();
  fsWorker.postMessage({ type: 'fs-register', client: info.pid, sab: info.sab, port: port2 }, [port2]);
  w.postMessage({ type: 'init', sab: info.sab, spec: info.spec, fsPort: port1 }, [port1]);
  return { postMessage: m => w.postMessage(m), terminate() { w.terminate(); workers.delete(w); fsWorker.postMessage({ type: 'fs-unregister', client: info.pid }); } };
} });
const sleep = ms => new Promise(r => setTimeout(r, ms));
const wait = async (fn, why) => { const end = Date.now() + 5000; while (!fn() && Date.now() < end) await sleep(10); assert.ok(fn(), why + '\n' + JSON.stringify([...output])); };
const text = pid => output.get(pid) || '';
const prompt = pid => text(pid).endsWith('$\x1b[0m ');
const send = (pid, s) => kernel.sendStdin(pid, s);
const results = [];
try {
  kernel.installCoreutils(); kernel.mkdirp('/work');
  kernel.writeFile('/work/tick.cjs', `const fs=require('fs'); console.log('TICK_READY'); setInterval(()=>fs.appendFileSync('/work/ticks','x'),30);`);
  const opts = { cwd: '/work', env: { PATH: '/bin' } };
  const a = kernel.launch('sh', [], opts), b = kernel.launch('sh', [], opts);
  await wait(() => text(a).includes('shell') && text(b).includes('shell'), 'two shells boot');
  send(a, 'node tick.cjs &\r');
  await wait(() => text(a).includes('TICK_READY'), 'background starts');
  send(a, 'jobs\r'); await wait(() => text(a).includes('[1] Running'), 'jobs reports running');
  send(b, 'echo shared > shared.txt\r');
  await wait(() => kernel.fs.exists('/work/shared.txt'), 'second shell writes');
  send(a, 'cat shared.txt\r'); await wait(() => /\nshared\n/.test(text(a)) && prompt(a), 'first shell reads shared bytes');
  results.push('two shells / shared filesystem / background jobs');
  send(a, 'fg %1\r'); await sleep(100); send(a, '\x03');
  await wait(() => ![...kernel.procs.values()].some(p => p.parentPid === a), 'fg Ctrl+C removes job subtree');
  const ticks = kernel.fs.readFile('/work/ticks').length; await sleep(120);
  assert.equal(kernel.fs.readFile('/work/ticks').length, ticks, 'interrupted child stops writing');
  send(a, 'echo resumed\r'); await wait(() => /\nresumed\n/.test(text(a)) && prompt(a), 'prompt usable after fg interrupt');
  results.push('fg / Ctrl+C / no residual writer / prompt restored');
  send(a, 'node tick.cjs &\r'); await wait(() => (text(a).match(/TICK_READY/g) || []).length === 2, 'second background job');
  send(a, 'kill %2\r'); await wait(() => ![...kernel.procs.values()].some(p => p.parentPid === a), 'kill removes subtree');
  send(a, 'jobs\r'); await wait(() => text(a).includes('[2] Done (143)'), 'killed job status retained and reaped');
  send(a, 'echo bad & echo wrong\r'); await wait(() => text(a).includes('supported background syntax'), 'unsupported compound rejected');
  send(a, 'echo "literal&"\r'); await wait(() => /\nliteral&\n/.test(text(a)) && prompt(a), 'quoted ampersand preserved');
  results.push('kill / completed jobs / compound rejection / quoted ampersand');
  send(a, 'node tick.cjs &\r'); await wait(() => (text(a).match(/TICK_READY/g) || []).length === 3, 'third job');
  send(a, 'exit\r'); await wait(() => !kernel.procs.has(a), 'exit terminates shell');
  assert.ok(kernel.procs.has(b));
  assert.equal([...kernel.procs.values()].filter(p => p.parentPid === a).length, 0);
  send(b, 'echo survivor\r'); await wait(() => /\nsurvivor\n/.test(text(b)) && prompt(b), 'other shell survives');
  send(b, 'echo pipeline | cat > pipeline.txt &\r');
  await wait(() => kernel.fs.exists('/work/pipeline.txt') && kernel.fs.readFile('/work/pipeline.txt') === 'pipeline\n', 'background pipeline redirect');
  results.push('background pipeline streams and redirects');
  send(b, '\x04'); await wait(() => !kernel.procs.has(b), 'EOF exits shell');
  results.push('exit child cleanup / sibling isolation / Ctrl+D');
  const c = kernel.launch('sh', [], { ...opts, terminal: { cols: 101, rows: 31 } });
  const d = kernel.launch('sh', [], { ...opts, terminal: { cols: 90, rows: 25 } });
  await wait(() => prompt(c) && prompt(d), 'geometry shells ready');
  kernel.writeFile('/work/terminal.cjs', `
    const fs=require('fs');
    const size=()=>process.stdout.getWindowSize().join('x');
    console.log('GEOMETRY:'+size());
    process.stdout.on('resize',()=>console.log('RESIZE:'+size()+':'+process.stderr.columns+'x'+process.stderr.rows));
    process.on('SIGWINCH',()=>console.log('WINCH:'+size()));
    process.on('SIGINT',()=>{fs.writeFileSync('/work/caught','yes');console.log('CAUGHT_INT');});
    process.stdin.on('end',()=>console.log('UNEXPECTED_EOF'));
    process.stdin.on('data',d=>{console.log('OWNED:'+d.toString().trim());if(d.toString().includes('finish'))process.exit(0);});
  `);
  send(c, 'node terminal.cjs &\r');
  await wait(() => text(c).includes('GEOMETRY:101x31'), 'spawn geometry inherited through background wrapper');
  send(c, 'echo prompt-owner\r');
  await wait(() => /\nprompt-owner\n/.test(text(c)) && prompt(c), 'background does not steal shell input');
  assert.ok(!text(c).includes('OWNED:') && !text(c).includes('UNEXPECTED_EOF'));
  kernel.resizeTerminal(c, { cols: 73, rows: 17 });
  await wait(() => text(c).includes('RESIZE:73x17:73x17') && text(c).includes('WINCH:73x17'), 'live descendant dimensions and resize/SIGWINCH');
  kernel.resizeTerminal(c, { cols: 73, rows: 17 }); await sleep(60);
  assert.equal((text(c).match(/RESIZE:/g) || []).length, 1, 'same geometry emits no duplicate event');
  assert.throws(() => kernel.resizeTerminal(c, { cols: 0, rows: 20 }), RangeError);
  send(d, `node -e "console.log('SIBLING:'+process.stdout.columns+'x'+process.stdout.rows)"\r`);
  await wait(() => /\nSIBLING:90x25\n/.test(text(d)) && prompt(d), 'sibling geometry isolation');
  send(c, 'fg %1\r'); await sleep(80); send(c, 'hello\r');
  await wait(() => text(c).includes('OWNED:hello'), 'fg gives live stdin to background reader');
  send(c, '\x03'); await wait(() => text(c).includes('CAUGHT_INT'), 'SIGINT delivered to guest handler');
  assert.equal(kernel.fs.readFile('/work/caught'), 'yes');
  send(c, 'finish\r'); await wait(() => text(c).includes('OWNED:finish') && prompt(c), 'handler survives interrupt and owns subsequent input');
  send(c, `node -e "console.log('LATE:'+process.stdout.columns+'x'+process.stdout.rows)"\r`);
  await wait(() => /\nLATE:73x17\n/.test(text(c)) && prompt(c), 'new child inherits latest geometry');
  send(c, `node -e "try{process.kill(process.pid,'SIGSTOP')}catch(e){console.log('UNSUPPORTED:'+e.code)}"\r`);
  await wait(() => /\nUNSUPPORTED:ENOTSUP\n/.test(text(c)) && prompt(c), 'unsupported suspension rejects');
  send(c, `node -e "console.log('BUSY_READY');while(true){}"\r`);
  await wait(() => text(c).includes('\nBUSY_READY\n'), 'uncooperative child running');
  kernel.stop(c); await wait(() => !kernel.procs.has(c), 'force stop handles uncooperative worker');
  assert.ok(kernel.procs.has(d)); kernel.stop(d);
  let interrupted;
  const intPid = kernel.launch('node', ['-e', "process.kill(process.pid,'SIGINT');setInterval(()=>{},1000)"], opts);
  kernel.procs.get(intPid).onExit = result => { interrupted = result; };
  await wait(() => interrupted, 'unhandled self SIGINT exits');
  assert.equal(interrupted.code, 130, 'unhandled SIGINT status');
  results.push('spawn/live/late dimensions; resize and SIGWINCH; duplicate/invalid resize; sibling isolation; foreground stdin transfer; catchable SIGINT survives; unsupported suspension; forced busy-worker cleanup');
  console.log(JSON.stringify({ phase: 'complete', results }, null, 2));
} finally { clearTimeout(timeout); for (const w of workers) await w.terminate(); }
