const { WASI } = require('node:wasi');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const wasi = new WASI({version:'preview1',preopens:{'/':'/workspace'}});
const memory = new WebAssembly.Memory({initial:1});
wasi.initialize({exports:{memory}});
const b = new Uint8Array(memory.buffer), d = new DataView(memory.buffer), w = wasi.wasiImport;
const put = (p,s) => b.set(Buffer.from(s),p);
put(100,'wasi-positional.txt');
assert.equal(w.path_open(3,0,100,19,1|8, (1n<<1n)|(1n<<6n),0n,0,200),0);
const fd=d.getUint32(200,true);
put(300,'abcd'); d.setUint32(32,300,true);d.setUint32(36,4,true);
assert.equal(w.fd_write(fd,32,1,64),0);
put(300,'XY');d.setUint32(36,2,true);
assert.equal(w.fd_pwrite(fd,32,1,1n,64),0);
assert.equal(d.getUint32(64,true),2);
assert.equal(w.fd_seek(fd,0n,1,72),0);
assert.equal(d.getBigUint64(72,true),4n);
assert.equal(w.fd_pwrite(1,32,1,0n,64),70);
assert.equal(w.fd_pwrite(2,32,1,0n,64),70);
assert.equal(w.fd_pwrite(999,32,1,0n,64),8);
assert.equal(w.fd_pwrite(fd,32,1,9007199254740992n,64),28);
assert.equal(w.fd_pwrite(fd,65532,1,0n,64),28);
memory.grow(1);
const grown = new DataView(memory.buffer), grownBytes = new Uint8Array(memory.buffer);
grownBytes.set(Buffer.from('!?'),70000);
grown.setUint32(32,70000,true);grown.setUint32(36,1,true);
grown.setUint32(40,70001,true);grown.setUint32(44,1,true);
assert.equal(w.fd_pwrite(fd,32,2,4n,64),0);
assert.equal(grown.getUint32(64,true),2);
assert.equal(w.fd_seek(fd,0n,1,72),0);
assert.equal(grown.getBigUint64(72,true),4n);
assert.equal(w.fd_close(fd),0);
assert.equal(fs.readFileSync('/workspace/wasi-positional.txt','utf8'),'aXYd!?');
console.log('WASI_POSITIONAL_PASS');
const libc = new WASI({version:'preview1',preopens:{'/workspace':'/workspace'}});
const instance = new WebAssembly.Instance(new WebAssembly.Module(fs.readFileSync('/wasm-tui/positional.wasm')),libc.getImportObject());
libc.initialize(instance);
assert.equal(instance.exports.probe(),0);
assert.equal(fs.readFileSync('/workspace/wasi-libc.txt','utf8'),'aXYd');
console.log('WASI_LIBC_PASS');
